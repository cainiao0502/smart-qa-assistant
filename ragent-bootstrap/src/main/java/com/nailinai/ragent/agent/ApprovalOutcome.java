package com.nailinai.ragent.agent;

/**
 * 人工审批的结果。
 *
 * <p>刻意区分「用户拒绝」与「无人可问」两种失败：前者是明确的业务决定，
 * 后者是通道能力缺失（同步接口调用、前端未实现审批、连接已断开）。
 * 策略层可以据此采取不同降级——目前两者都按不放行处理，但原因会分别写进观察，
 * 避免把「系统做不到」误报成「用户不同意」。</p>
 */
public enum ApprovalOutcome {

    /** 已获人工授权，可以执行 */
    APPROVED,

    /** 人工明确拒绝执行 */
    REJECTED,

    /** 当前请求没有可用的审批通道（超时、断线、或调用方未实现） */
    UNAVAILABLE
}
